// One-time codegen (run `npm run generate:icons` after upgrading bootstrap-icons).
// Reads SVGs from node_modules and writes them as inner-markup map so the app
// bundles icons offline with zero runtime dependency on the package layout.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const ICONS = [
  "filetype-html",
  "filetype-css",
  "filetype-scss",
  "filetype-js",
  "filetype-jsx",
  "filetype-tsx",
  "filetype-json",
  "filetype-md",
  "filetype-txt",
  "filetype-pdf",
  "filetype-png",
  "filetype-jpg",
  "filetype-gif",
  "filetype-svg",
  "filetype-mp3",
  "filetype-mp4",
  "filetype-mov",
  "filetype-wav",
  "filetype-doc",
  "filetype-docx",
  "filetype-xls",
  "filetype-xlsx",
  "filetype-ppt",
  "filetype-pptx",
  "filetype-csv",
  "filetype-xml",
  "filetype-yml",
  "filetype-py",
  "filetype-sh",
  "filetype-java",
  "filetype-rb",
  "filetype-php",
  "file-earmark-text",
  "file-earmark-code",
  "file-earmark-image",
  "file-earmark-music",
  "file-earmark-play",
  "file-earmark-zip",
  "file-earmark-pdf",
];

const paths = {};
for (const name of ICONS) {
  const svg = readFileSync(join(root, "node_modules", "bootstrap-icons", "icons", `${name}.svg`), "utf8");
  paths[name] = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .trim();
}

const out = `// AUTO-GENERATED by scripts/generate-file-icons.mjs — do not edit by hand.
// Glyphs: Bootstrap Icons (https://icons.getbootstrap.com), MIT © The Bootstrap Authors.
// Regenerate with: npm run generate:icons
export const FILETYPE_ICON_PATHS: Record<string, string> = ${JSON.stringify(paths, null, 2)};
`;

writeFileSync(join(root, "src", "components", "ui", "filetype-icons.ts"), out);
console.log(`Wrote ${ICONS.length} icons.`);
